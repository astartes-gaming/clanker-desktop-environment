#!/bin/sh
# Runs INSIDE the test VM as root (see build-vm.sh / vmctl.py provision).
# Installs CDE's runtime dependencies plus the staged CDE build, makes
# dtlogin the display manager and creates the test user.
set -eu
P=$(cd "$(dirname "$0")" && pwd)
export DEBIAN_FRONTEND=noninteractive

apt-get update -q
# Libraries the CDE binaries link against (computed on the build host),
# plus what CDE needs at runtime and a few test tools.
# shellcheck disable=SC2046
apt-get install -y -q --no-install-recommends $(cat "$P/runtime-pkgs.txt") \
    xserver-xorg-core xserver-xorg-input-libinput xauth \
    x11-xserver-utils x11-utils xfonts-base xfonts-utils \
    xfonts-100dpi xfonts-75dpi xfonts-100dpi-transcoded xfonts-75dpi-transcoded \
    ksh tcl rpcbind ncompress m4 cpp ncurses-term \
    dbus dbus-x11 dbus-user-session libpam-systemd \
    xterm dex xdotool gtk-3-examples xinput python3-evdev

# The staged CDE tree (built on the host with make install DESTDIR=...).
tar -xzf "$P/cde-stage.tar.gz" -C /
chown -R root:root /usr/dt /etc/pam.d/dtlogin /etc/pam.d/dtsession 2>/dev/null || true
chmod 4755 /usr/dt/bin/dtappgather 2>/dev/null || true
echo /usr/dt/lib > /etc/ld.so.conf.d/cde.conf
ldconfig
install -d -m 0755 /var/dt /var/dt/appconfig
install -d -m 1777 /var/dt/appconfig/appmanager /var/dt/tmp

# dtlogin as the display manager (unit generated by configure).
install -m 0644 "$P/dtlogin.service" /etc/systemd/system/dtlogin.service
ln -sf /etc/systemd/system/dtlogin.service \
       /etc/systemd/system/display-manager.service
systemctl enable rpcbind.service rpcbind.socket >/dev/null 2>&1 || true
systemctl set-default graphical.target

# Test account; the password is generated on the host (out/credentials).
id tester >/dev/null 2>&1 || useradd -m -s /bin/bash tester
printf 'tester:%s\n' "$(cat "$P/tester-password")" | chpasswd

apt-get clean
echo "PROVISION_OK"
